export const defaultProfiles = profileSource.map((profile) => ({
  ...profile,
  careers: profile.careers.map(withStyle),
  majors: profile.majors.map(withStyle),
}))

export const profileMap = Object.fromEntries(defaultProfiles.map((item) => [item.type, item]))
